export function freeElectiveText(language, key) {
    return FREE_ELECTIVE_LABELS[language]?.[key]
        || FREE_ELECTIVE_LABELS.th[key]
        || key;
}

export function localizedFreeElective(item, language, thKey, enKey) {
    if (language === 'en' && item?.[enKey]) {
        return item[enKey];
    }

    return item?.[thKey] || item?.[enKey] || '-';
}

export function formatFreeElectiveTerm(year, semester, language) {
    if (!year) {
        return '-';
    }

    const termLabel = language === 'en' ? 'Term' : 'ภาคเรียน';
    return `${year} · ${termLabel} ${semester || '-'}`;
}
